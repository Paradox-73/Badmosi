CELL_W, CELL_H = 6, 9
COLS = 16


def png(path, w, h, rows):
    raw = b"".join(b"\x00" + bytes(r) for r in rows)
    def chunk(t, d):
        c = struct.pack(">I", len(d)) + t + d
        return c + struct.pack(">I", zlib.crc32(t + d) & 0xFFFFFFFF)
    data = b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, 6, 0, 0, 0))
    data += chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")
    Path(path).write_bytes(data)


def main():
    chars = [" "] + list(G.keys())
    lower = [c.lower() for c in G if c.isalpha()]
    entries = []  # (codepoint, glyph key)
    for c in chars:
        entries.append((ord(c), c))
    for c in lower:
        entries.append((ord(c), c.upper()))
    keys = chars
    rows_n = (len(keys) + COLS - 1) // COLS
    w, h = COLS * CELL_W, rows_n * CELL_H
    pix = [[0] * (w * 4) for _ in range(h)]
    pos = {}
    for i, k in enumerate(keys):
        cx, cy = (i % COLS) * CELL_W, (i // COLS) * CELL_H
        pos[k] = (cx, cy)
        if k == " ":
            continue
        for y, line in enumerate(G[k]):
            for x, ch in enumerate(line):
                if ch == "#":
                    px = (cx + x) * 4
                    pix[cy + y + 1][px:px + 4] = [255, 255, 255, 255]
    out = Path("assets/fonts")
    out.mkdir(parents=True, exist_ok=True)
    png(out / "pix5x7.png", w, h, pix)
    lines = [
        'info face="Pix5x7" size=8 bold=0 italic=0 charset="" unicode=1 stretchH=100 smooth=0 aa=1 padding=0,0,0,0 spacing=0,0',
        f"common lineHeight={CELL_H} base=8 scaleW={w} scaleH={h} pages=1 packed=0",
        'page id=0 file="pix5x7.png"',
        f"chars count={len(entries)}",
    ]
    for cp, k in entries:
        cx, cy = pos[k]
        lines.append(
            f"char id={cp} x={cx} y={cy} width={CELL_W} height={CELL_H} xoffset=0 yoffset=0 xadvance={CELL_W} page=0 chnl=15"
        )
    (out / "pix5x7.fnt").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(entries)} glyphs, atlas {w}x{h}")


if __name__ == "__main__":
    main()
